-- Manual CRM phase 1. Apply explicitly BEFORE deploying the corresponding code.
-- Does not update leads, search_runs, tags, funnels, stages, notes, or stage history.
-- Existing cards remain managed_manually=false with sales_outcome=NULL.
BEGIN;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '60s';
SELECT pg_advisory_xact_lock(hashtext('gmapscrap_manual_crm_phase1'));

ALTER TABLE public.crm_leads
    ADD COLUMN IF NOT EXISTS managed_manually boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS estimated_value numeric(14,2),
    ADD COLUMN IF NOT EXISTS currency varchar(3) NOT NULL DEFAULT 'BRL',
    ADD COLUMN IF NOT EXISTS sales_outcome varchar(10),
    ADD COLUMN IF NOT EXISTS lost_reason text,
    ADD COLUMN IF NOT EXISTS closed_at timestamptz,
    ADD COLUMN IF NOT EXISTS version integer NOT NULL DEFAULT 1;

DO $$ BEGIN
    IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid='public.crm_leads'::regclass AND conname='ck_crm_leads_value') THEN
        ALTER TABLE public.crm_leads ADD CONSTRAINT ck_crm_leads_value CHECK (estimated_value IS NULL OR estimated_value >= 0);
    END IF;
    IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid='public.crm_leads'::regclass AND conname='ck_crm_leads_outcome') THEN
        ALTER TABLE public.crm_leads ADD CONSTRAINT ck_crm_leads_outcome CHECK (sales_outcome IS NULL OR sales_outcome IN ('open','won','lost'));
    END IF;
    IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid='public.crm_leads'::regclass AND conname='ck_crm_leads_lost_reason') THEN
        ALTER TABLE public.crm_leads ADD CONSTRAINT ck_crm_leads_lost_reason CHECK (sales_outcome IS NULL OR sales_outcome <> 'lost' OR lost_reason IS NOT NULL AND length(trim(lost_reason)) > 0);
    END IF;
    IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid='public.crm_leads'::regclass AND conname='ck_crm_leads_won_value') THEN
        ALTER TABLE public.crm_leads ADD CONSTRAINT ck_crm_leads_won_value CHECK (sales_outcome IS NULL OR sales_outcome <> 'won' OR estimated_value IS NOT NULL);
    END IF;
    IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid='public.crm_leads'::regclass AND conname='ck_crm_leads_currency') THEN
        ALTER TABLE public.crm_leads ADD CONSTRAINT ck_crm_leads_currency CHECK (currency IN ('BRL','USD','EUR','GBP','CAD','AUD'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.crm_activities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crm_lead_id integer NOT NULL REFERENCES public.crm_leads(id) ON DELETE RESTRICT,
    kind varchar(20) NOT NULL CONSTRAINT ck_crm_activities_kind CHECK (kind IN ('note','call','whatsapp','meeting','system')),
    body text NOT NULL CHECK (length(trim(body)) > 0),
    details jsonb,
    actor varchar(255) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_crm_activities_card_created ON public.crm_activities(crm_lead_id, created_at, id);

CREATE TABLE IF NOT EXISTS public.crm_follow_ups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crm_lead_id integer NOT NULL REFERENCES public.crm_leads(id) ON DELETE RESTRICT,
    title varchar(255) NOT NULL CHECK (length(trim(title)) > 0),
    due_at timestamptz NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'pending' CONSTRAINT ck_crm_follow_ups_status CHECK (status IN ('pending','completed','cancelled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz,
    version integer NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS ix_crm_follow_ups_status_due ON public.crm_follow_ups(status,due_at);
CREATE INDEX IF NOT EXISTS ix_crm_follow_ups_card ON public.crm_follow_ups(crm_lead_id);

CREATE OR REPLACE FUNCTION public.gmapscrap_crm_activity_immutable() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    RAISE EXCEPTION 'CRM activities are append-only' USING ERRCODE='55000';
END $$;
DROP TRIGGER IF EXISTS crm_activities_immutable ON public.crm_activities;
CREATE TRIGGER crm_activities_immutable BEFORE UPDATE OR DELETE ON public.crm_activities
    FOR EACH ROW EXECUTE FUNCTION public.gmapscrap_crm_activity_immutable();
DROP TRIGGER IF EXISTS crm_activities_no_truncate ON public.crm_activities;
CREATE TRIGGER crm_activities_no_truncate BEFORE TRUNCATE ON public.crm_activities
    FOR EACH STATEMENT EXECUTE FUNCTION public.gmapscrap_crm_activity_immutable();

ALTER TABLE public.crm_activities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.crm_follow_ups ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.crm_activities, public.crm_follow_ups FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.crm_activities_id_seq, public.crm_follow_ups_id_seq FROM PUBLIC;
REVOKE ALL ON FUNCTION public.gmapscrap_crm_activity_immutable() FROM PUBLIC;
DO $$ DECLARE api_role text; BEGIN
    FOREACH api_role IN ARRAY ARRAY['anon','authenticated'] LOOP
        IF EXISTS (SELECT FROM pg_roles WHERE rolname=api_role) THEN
            EXECUTE format('REVOKE ALL ON public.crm_activities, public.crm_follow_ups FROM %I',api_role);
            EXECUTE format('REVOKE ALL ON SEQUENCE public.crm_activities_id_seq, public.crm_follow_ups_id_seq FROM %I',api_role);
        END IF;
    END LOOP;
END $$;
-- The existing owner/backend connection retains access. No browser RLS policies.
COMMIT;
